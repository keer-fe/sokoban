"""Build canvas clipping bands from the eight disconnected sprite silhouettes.

Run from the repository root with Python + Pillow after changing the sheet.
No image files are modified. Checks all eight poses for neighboring-pose leaks.
"""
from pathlib import Path
import json
from PIL import Image

root = Path(__file__).resolve().parent.parent
image = Image.open(root / 'assets/animation/push-character-cycle-v2.png')
alpha = image.getchannel('A')
seen = set()
poses = []
for y in range(80, 280):
    for x in range(image.width):
        if (x, y) in seen or alpha.getpixel((x, y)) < 64:
            continue
        pending = [(x, y)]
        seen.add((x, y))
        pixels = set()
        while pending:
            px, py = pending.pop()
            pixels.add((px, py))
            for point in ((px-1, py), (px+1, py), (px, py-1), (px, py+1)):
                qx, qy = point
                if (0 <= qx < image.width and 80 <= qy < 280
                        and point not in seen and alpha.getpixel(point) >= 64):
                    seen.add(point)
                    pending.append(point)
        if len(pixels) > 1000:
            poses.append(pixels)
poses.sort(key=lambda pixels: min(x for x, y in pixels))
assert len(poses) == 8
all_pixels = set().union(*poses)
result = []
for pixels in poses:
    # Two pixels of padding preserve antialiased hair, hats, hands and shoes.
    rows = {}
    for x, y in pixels:
        for dy in range(-2, 3):
            bounds = rows.setdefault(y + dy, [x - 2, x + 3])
            bounds[0] = min(bounds[0], x - 2)
            bounds[1] = max(bounds[1], x + 3)
    foreign = all_pixels - pixels
    for x, y in foreign:
        assert y not in rows or not rows[y][0] <= x < rows[y][1], (x, y)
    for x, y in pixels:
        assert rows[y][0] <= x < rows[y][1]
    bands = []
    for y, (left, right) in sorted(rows.items()):
        if bands and bands[-1][0] + bands[-1][1] == y and bands[-1][2:] == [left, right]:
            bands[-1][1] += 1
        else:
            bands.append([y, 1, left, right])
    result.append(bands)
target = root / 'src/pages/home/push-masks.js'
target.write_text('// Generated by tools/build-push-masks.py; [y, height, left, right].\n'
                  + 'export const PUSH_MASKS = ' + json.dumps(result, separators=(',', ':')) + ';\n')
print('Verified 8 masks: every silhouette retained; zero neighboring silhouette pixels.')
